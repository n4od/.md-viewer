<#
  Measures the things that are easy to argue about: time to a *visible* window,
  memory of the app's own process versus the WebView2 processes it spawns, and
  whether a second launch reuses the running instance.

  Usage:
    powershell -ExecutionPolicy Bypass -File scripts\measure.ps1
    powershell -ExecutionPolicy Bypass -File scripts\measure.ps1 -WriteReport

  -WriteReport also writes PERFORMANCE.md next to the repository root.
#>
[CmdletBinding()]
param(
    [string]$ExePath,
    [string]$Document,
    [switch]$WriteReport
)

$ErrorActionPreference = 'Stop'

$scriptRoot = $PSScriptRoot
if ([string]::IsNullOrEmpty($scriptRoot)) {
    $scriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Definition
}
$repoRoot = [System.IO.Path]::GetFullPath((Join-Path $scriptRoot '..'))

if ([string]::IsNullOrEmpty($ExePath)) {
    $ExePath = Join-Path $repoRoot 'src-tauri\target\release\mdviewer.exe'
}
if ([string]::IsNullOrEmpty($Document)) {
    $Document = Join-Path $repoRoot 'sample.md'
}
if (-not (Test-Path $ExePath)) { throw "Not built yet: $ExePath" }
if (-not (Test-Path $Document)) { throw "Missing test document: $Document" }

$second = Join-Path (Split-Path -Parent $Document) 'sample-notes.md'

function Stop-Viewer {
    Get-Process mdviewer -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Sleep -Milliseconds 400
}

function Get-Descendants {
    param([int]$RootId)
    $all = Get-CimInstance Win32_Process | Select-Object ProcessId, ParentProcessId, Name
    $ids = @($RootId)
    $changed = $true
    while ($changed) {
        $changed = $false
        foreach ($item in $all) {
            if ($ids -contains [int]$item.ParentProcessId -and $ids -notcontains [int]$item.ProcessId) {
                $ids += [int]$item.ProcessId
                $changed = $true
            }
        }
    }
    return $ids
}

function Measure-Set {
    param([int]$RootId)
    $ids = Get-Descendants -RootId $RootId
    $result = @()
    foreach ($id in $ids) {
        $proc = Get-Process -Id $id -ErrorAction SilentlyContinue
        if ($null -eq $proc) { continue }
        $result += [pscustomobject]@{
            Name      = $proc.ProcessName
            Id        = $proc.Id
            WorkingMB = [math]::Round($proc.WorkingSet64 / 1MB, 1)
            PrivateMB = [math]::Round($proc.PrivateMemorySize64 / 1MB, 1)
        }
    }
    return $result
}

Stop-Viewer

# --- 1. Cold start: launch with a document, wait for the visible window -----
$watch = [System.Diagnostics.Stopwatch]::StartNew()
$first = Start-Process -FilePath $ExePath -ArgumentList "`"$Document`"" -PassThru

$title = ''
while ($watch.ElapsedMilliseconds -lt 20000) {
    Start-Sleep -Milliseconds 5
    $first.Refresh()          # MainWindowTitle is cached until refreshed
    if ($first.HasExited) { break }
    if ($first.MainWindowHandle -ne 0 -and $first.MainWindowTitle -like '*MD Viewer*') {
        $title = $first.MainWindowTitle
        break
    }
}
$watch.Stop()
$firstMs = $watch.ElapsedMilliseconds

Start-Sleep -Milliseconds 1200    # let WebView2 children settle
$measurements = Measure-Set -RootId $first.Id
$ownProcs = $measurements | Where-Object { $_.Name -eq 'mdviewer' }
$webProcs = $measurements | Where-Object { $_.Name -eq 'msedgewebview2' }

# --- 2. Second launch with another document: one instance, new document -----
$before = (Get-Process mdviewer -ErrorAction SilentlyContinue).Count
if (Test-Path $second) {
    Start-Process -FilePath $ExePath -ArgumentList "`"$second`"" | Out-Null
}
Start-Sleep -Milliseconds 1500
$afterProcs = Get-Process mdviewer -ErrorAction SilentlyContinue
$afterCount = @($afterProcs).Count
$afterTitle = ($afterProcs | Where-Object { $_.MainWindowTitle -like '*MD Viewer*' } | Select-Object -First 1).MainWindowTitle

$report = [System.Collections.Generic.List[string]]::new()
$report.Add('# MD Viewer - measured performance')
$report.Add('')
$report.Add("Generated by ``scripts/measure.ps1`` on $([System.DateTime]::Now.ToString('yyyy-MM-dd HH:mm')).")
$report.Add('')
$report.Add('| Metric | Value |')
$report.Add('| :-- | :-- |')
$report.Add("| Time to visible window (release build, with a document) | **${firstMs} ms** |")
$report.Add("| Window title after launch | ``$title`` |")
$report.Add("| mdviewer.exe processes | $(@($ownProcs).Count) |")
$report.Add("| mdviewer.exe working set (sum) | **$([math]::Round(($ownProcs | Measure-Object WorkingMB -Sum).Sum, 1)) MB** |")
$report.Add("| mdviewer.exe private bytes (sum) | $([math]::Round(($ownProcs | Measure-Object PrivateMB -Sum).Sum, 1)) MB |")
$report.Add("| WebView2 child processes | $(@($webProcs).Count) |")
$report.Add("| WebView2 working set (sum) | $([math]::Round(($webProcs | Measure-Object WorkingMB -Sum).Sum, 1)) MB |")
$report.Add("| Everything, working set (sum) | **$([math]::Round(($measurements | Measure-Object WorkingMB -Sum).Sum, 1)) MB** |")
$report.Add("| Instances after second launch | $afterCount (one window reused) |")
$report.Add("| Title after opening a second file | ``$afterTitle`` |")
$report.Add('')
$report.Add('## Process breakdown')
$report.Add('')
$report.Add('| Process | PID | Working set | Private bytes |')
$report.Add('| :-- | --: | --: | --: |')
foreach ($row in ($measurements | Sort-Object Name)) {
    $report.Add("| $($row.Name) | $($row.Id) | $($row.WorkingMB) MB | $($row.PrivateMB) MB |")
}
$report.Add('')
$report.Add('Notes: WebView2 always runs the renderer, GPU and utility work in separate')
$report.Add('processes, so the total is what a user sees in Task Manager, while the Rust')
$report.Add('process on its own is the app''s own footprint.')

$text = ($report -join "`n")

# Write before emitting: a consumer that stops the pipeline early
# (`... -WriteReport | Select-Object -First 10`) must not skip the file write.
if ($WriteReport) {
    $path = Join-Path $repoRoot 'PERFORMANCE.md'
    Set-Content -Path $path -Value $text -Encoding UTF8
    Write-Host "`nWritten: $path"
}

Write-Output $text

Stop-Viewer
